"""Independent RFC 4506 binary128 byte / rational-widening corpus (synthetic, MIT).

No MoonXDR functions are used by the oracle. Python integers supply 128-bit
network words; finite IEEE64 numbers are converted through exact integer ratios,
not the implementation's exponent/payload shift algorithm. No binary128 arithmetic
conformance is claimed. --check verifies checked-in fixtures without rewriting.
"""
from pathlib import Path
import argparse
import random
import struct

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'reference128_wbtest.mbt'

def widen(bits):
    sign = bits >> 63
    exponent = (bits >> 52) & 2047
    payload = bits & ((1 << 52) - 1)
    if exponent == 2047:
        return (sign << 127) | (32767 << 112) | (payload << 60)
    value = struct.unpack('>d', bits.to_bytes(8, 'big'))[0]
    if value == 0:
        return sign << 127
    numerator, denominator = abs(value).as_integer_ratio()
    e = numerator.bit_length() - denominator.bit_length()
    if e >= 0:
        if numerator < denominator << e:
            e -= 1
    elif numerator << -e < denominator:
        e -= 1
    shift = 112 - e
    if shift >= 0:
        scaled, remainder = divmod(numerator << shift, denominator)
    else:
        scaled, remainder = divmod(numerator, denominator << -shift)
    assert remainder == 0 and (1 << 112) <= scaled < (1 << 113)
    return (sign << 127) | ((e + 16383) << 112) | (scaled - (1 << 112))

def corpus():
    rng = random.Random(4506128)
    raw = [0, 1, 1 << 127, (1 << 128) - 1]
    for exponent in [0, 1, 16382, 16383, 32766, 32767]:
        for fraction in [0, 1, (1 << 111), (1 << 112) - 1]:
            for sign in [0, 1]:
                raw.append((sign << 127) | (exponent << 112) | fraction)
    raw += [rng.getrandbits(128) for _ in range(128)]
    doubles = [0, 1, 2, (1 << 52) - 1, 1 << 52, 0x3ff0000000000000,
               0x7fefffffffffffff, 0x7ff0000000000000, 0x7ff0000000000001,
               0x7ff8000000000001, 0x8000000000000000, 0xffffffffffffffff]
    doubles += [rng.getrandbits(64) for _ in range(128)]
    raw = list(dict.fromkeys(raw))
    doubles = list(dict.fromkeys(doubles))
    lines = ['// Synthetic oracle corpus generated by scripts/reference128.py; excluded from production LOC.', '///|',
             'test "independent Python integer binary128 network corpus" {']
    for n in raw:
        high, low = n >> 64, n & ((1 << 64) - 1)
        lines += [f'  let q : Quadruple = {{ high: 0x{high:016x}UL, low: 0x{low:016x}UL }}',
                  f'  let expected = "{n.to_bytes(16, "big").hex()}"',
                  '  let w = Writer::new()', '  w.write_quadruple(q)',
                  '  assert_eq(to_hex(w.bytes()), expected)',
                  '  assert_eq(Reader::new(from_hex(expected)).read_quadruple(), q)']
    lines += ['}', '///|', 'test "independent Python rational exact binary64 widening corpus" {']
    for b in doubles:
        expected = widen(b).to_bytes(16, 'big').hex()
        lines += [f'  assert_eq(Quadruple::from_double(0x{b:016x}UL.reinterpret_as_double()).to_hex(), "{expected}")']
    lines += ['}', '']
    return '\n'.join(lines), len(raw), len(doubles)

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, raw_count, double_count = corpus()
    if args.check:
        normalize = lambda s: ''.join(s.split()).replace(',)', ')').replace(',]', ']').replace(',}', '}')
        assert normalize(OUT.read_text(encoding='utf-8-sig')) == normalize(content), 'binary128 corpus changed'
    else:
        OUT.write_text(content, encoding='utf-8')
    print(f'binary128 network vectors={raw_count}; rational binary64 widening vectors={double_count}')

