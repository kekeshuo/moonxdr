"""Independent stdlib struct oracle. Reproduce committed vectors with --check.
No MoonBit implementation code is used to calculate expected bytes.
"""
import argparse
import pathlib
import random
import struct

ROOT = pathlib.Path(__file__).resolve().parents[1]

def vectors():
    rng = random.Random(45065531)
    edges = [(-2147483648, 0, -9223372036854775808, 18446744073709551615),
             (2147483647, 4294967295, 9223372036854775807, 0)]
    for i in range(64):
        a, b, c, d = edges[i] if i < 2 else (rng.randrange(-2**31, 2**31), rng.randrange(2**32), rng.randrange(-2**63, 2**63), rng.randrange(2**64))
        f, g = rng.randrange(-100000, 100000) / 8, rng.randrange(-100000, 100000) / 16
        yield a, b, c, d, f, g, struct.pack('>iIqQfd', a, b, c, d, f, g).hex()

def render():
    rows = []
    for a,b,c,d,f,g,h in vectors():
        rows.append(f'    ({a}, {b}U, {c}L, {d}UL, {f}F, {g}, "{h}"),')
    return '''// Generated by scripts/reference_vectors.py; test data only, excluded from production LOC.
///|
test "64 independent Python struct scalar vectors" {
  let vectors : Array[(Int, UInt, Int64, UInt64, Float, Double, String)] = [
''' + '\n'.join(rows) + '''
  ]
  for (a, b, c, d, f, g, hex) in vectors {
    let w = Writer::new()
    w.write_int(a)
    w.write_uint(b)
    w.write_hyper(c)
    w.write_uhyper(d)
    w.write_float(f)
    w.write_double(g)
    assert_eq(to_hex(w.bytes()), hex)
    let r = Reader::new(from_hex(hex))
    assert_eq(r.read_int(), a)
    assert_eq(r.read_uint(), b)
    assert_eq(r.read_hyper(), c)
    assert_eq(r.read_uhyper(), d)
    assert_eq(r.read_float(), f)
    assert_eq(r.read_double(), g)
    r.finish()
  }
}
'''

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    path = ROOT / 'reference_wbtest.mbt'
    text = render()
    # Moon fmt changes indentation only if generator and formatter disagree.
    if args.check:
        normalize = lambda s: ''.join(s.split()).replace(',)', ')').replace(',]', ']')
        assert normalize(path.read_text(encoding='utf-8')) == normalize(text), 'reference vectors changed'
    else:
        path.write_text(text, encoding='utf-8', newline='\n')
    print('64 scalar vectors, 384 field encodings independently calculated')

if __name__ == '__main__':
    main()
